def table():
    """The paper's Table (tab:bodyfitted) from the JSON outputs. Total = tet(rec.)/hex(vox.); Dom. = tet/hex of the
    full design domain; Elem. = tet(vox.)/hex(vox.); Rec. = tet(rec.)/tet(vox.); Vol. = recovered / voxel volume."""
    rows = []
    for case, label in TABLE:
        a, v = (os.path.join(OUT, case, name) for name in ("analysis.json", "voxel_tet.json"))
        missing = [os.path.basename(f) for f in (a, v) if not os.path.exists(f)]
        if missing:
            rows.append((label, f"missing {', '.join(missing)} in {os.path.relpath(os.path.join(OUT, case), ROOT)}"))
            continue
        with open(a) as fh:
            r = json.load(fh)
        with open(v) as fh:
            vt = json.load(fh)
        c = r["comparison"]
        rows.append((label, r["tet_part"]["dofs"], c["volume_tet_part_over_hex_design"],
                     c["compliance_tet_over_hex_part"], c["compliance_tet_over_hex_full_domain"],
                     vt["tet_voxel_over_hex_voxel"], r["tet_part"]["compliance"] / vt["tet_voxel"]["compliance"]))
    w = max(len(label) for _c, label in TABLE)
    print(f"{'Part':<{w}}  {'Tet DOF':>9}  {'Vol.':>5}  {'Total':>5}  {'Dom.':>5}  {'Elem.':>5}  {'Rec.':>5}")
    for row in rows:
        if isinstance(row[1], str):
            print(f"{row[0]:<{w}}  {row[1]}")
        else:
            print(f"{row[0]:<{w}}  {row[1]:>9,}  " + "  ".join(f"{x:5.3f}" for x in row[2:]))
    print("\nLaTeX rows:")
    for row in rows:
        if not isinstance(row[1], str):
            dof = f"{row[1]:,}".replace(",", "\\,")
            print(f"{row[0]} & {dof} & " + " & ".join(f"{x:.3f}" for x in row[2:]) + " \\\\")


