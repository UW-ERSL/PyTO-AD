"""Body-fitted re-analysis of optimized designs: voxel (hex8) design vs recovered smooth STL meshed with tetrahedra.

For each case the final optimized design on the benchmark's hex mesh is turned into a smooth STL with the same
post-processing the GUI uses (pyto.io.topopt_stl_recovery: CNN smoothing of the nodal density, void iso-surface at
0.5, boolean subtraction from the design-domain STL; CNN seeded for reproducibility). The STL is re-meshed with
TetGen (10-node tetrahedra) and analysed with the same supports and load as the benchmark. Objectives are compared
with the hex (voxel, not body-fitted) analysis of the 0/1 design:
  compliance                     f . u
  stress (L-bracket stress case) von Mises: volume-weighted p-norm (p = 6, the optimizer's exponent) and maximum,
                                 computed the same way on both meshes (hex: element centres of solid elements,
                                 tet: the 4 Gauss points of every element)
Calibration: the same comparison for the full design domain (hex at density 1 vs tet of the domain STL) measures the
hex-vs-tet difference that has nothing to do with the design (voxelized boundary, element type, nodal loads).

Cases:
  LBracket_stress     3D thick L-bracket, minimize p-norm stress, volume <= 0.25 (Results/AD_Showcase/LBracket_stress,
                      produced by pyto.examples_benchmarks.ad_showcase)
  EdgeCantilever      benchmark EdgeCantilever, compliance, volume 0.25 (Results/AD_Showcase/EdgeCantilever,
                      produced by pyto.examples_benchmarks.ad_showcase)
  ThreeHoleBracket    benchmark ThreeHoleBracketThick, compliance, volume 0.25 (optimized here: MMA, as the benchmark
                      sweep); supports and load on the cylindrical hole surfaces, which the hex mesh staircases
  ThreeHoleBracketGUI the part of the recorded GUI session (docs/paper/fig_gen/gui_session_threehole.py,
                      Results/GUISession_ThreeHole): ThreeHoleBracketThick with the benchmark's supports and load on
                      the GUI's mesh (62 849 elements, mesh request 67 000 elements = nDOFDesired 201 000, the same
                      mesh as nDOFDesired 200 000 of Fig. 1). Voxel design: the GUI's continuous density
                      (density.npy) >= 0.5, checked against the GUI's .vtu mesh; part: the GUI's own recovered STL
                      (no recover stage). Its full-domain calibration and like-for-like check are its own (this mesh).

Stages (each reuses what the previous ones saved; existing outputs are not regenerated by optimize / recover):
  optimize   design.npz on the hex mesh (from an existing run, an MMA run, or the GUI density)
  recover    recovered.stl (GUI recovery; not for ThreeHoleBracketGUI)
  analyze    analysis.json: hex design, hex full domain, tet part, tet full domain (TetGen + PARDISO, 0.5-3 M DOF)
  voxeltet   voxel_tet.json: the voxel design itself meshed with the same tets (like-for-like check)
  images     PNGs of design, recovered STL, tet mesh (and stress fields)
  table      prints the paper's Table (Part, Tet DOF, Vol., Total, Dom., Elem., Rec.) from the JSON outputs
  all        optimize, recover, analyze, images

Run from the repository root:
    export PYTHONPATH=src MPLBACKEND=Agg PYVISTA_OFF_SCREEN=true
    python -m pyto.examples_benchmarks.body_fitted_study <stage> [cases]
Output: Results/BodyFitted/<case>/ design.npz, recovered.stl, analysis.json, voxel_tet.json, *.png;
Results/BodyFitted/README.md (another folder: environment variable PYTO_BODY_FITTED_OUT)
"""
