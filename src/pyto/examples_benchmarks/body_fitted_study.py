def _grid(d, density=None):
    import pyvista as pv
    elems = d["elems"]
    cells = np.hstack([np.full((len(elems), 1), 8), elems]).ravel()
    g = pv.UnstructuredGrid(cells, np.full(len(elems), pv.CellType.HEXAHEDRON, dtype=np.uint8),
                            d["node_xyz"].astype(float))
    if density is not None:
        g.cell_data["density"] = density
    return g


def recover(case):
    """Smooth STL of the design with the GUI's recovery (CNN smoothing, void iso-surface, boolean subtraction)."""
    out = _path(case, "recovered.stl")
    if CASES[case].get("recovered") or os.path.exists(out):
        return
    import pyvista as pv
    import torch
    from pyto.io.topopt_stl_recovery import extract_isosurface_cnn, subtract_voids_from_stl
    d = np.load(_path(case, "design.npz"))
    nodal = _grid(d, d["final"]).cell_data_to_point_data()    # nodal density, as the GUI's .vtu export
    nodal.save(_path(case, "design.vtu"))
    # The CNN step works on the full regular grid around the part. Grid points outside the design domain must count
    # as MATERIAL: extract_isosurface_cnn would otherwise resample them as density 0 (void), and subtracting that
    # "void" from the domain STL shaves the part's own outer surface at voxel resolution (sharp fins and facets on
    # curved domain boundaries). With them as material only real voids are removed and the domain keeps its smooth boundary. For
    # box domains (every grid point is a mesh node) this changes nothing.
    xyz = d["node_xyz"]
    lo, h = xyz.min(0), np.array([np.diff(np.unique(xyz[:, k]))[0] for k in range(3)])
    idx = np.rint((xyz - lo) / h).astype(int)
    n = idx.max(0) + 1
    grid_density = np.ones(tuple(n))
    grid_density[idx[:, 0], idx[:, 1], idx[:, 2]] = np.asarray(nodal.point_data["density"])
    vtu = pv.ImageData(dimensions=tuple(n), spacing=tuple(h), origin=tuple(lo))
    vtu.point_data["density"] = grid_density.ravel(order="F")
    torch.manual_seed(0)
    np.random.seed(0)
    with contextlib.redirect_stdout(io.StringIO()):
        void = extract_isosurface_cnn(vtu)
        domain = pv.read(_domain(case)).clean().triangulate().compute_normals()
        part = subtract_voids_from_stl(domain, void)
    part.save(out)
    print(f"{case}: recovered STL, {part.n_cells} triangles, volume {part.volume:.4g} m^3 "
          f"(domain {domain.volume:.4g})", flush=True)


