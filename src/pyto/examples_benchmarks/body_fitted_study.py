def optimize(case):
    """The final design on the benchmark mesh: from an existing run, or a full MMA (AD) optimization as the sweep
    runs it."""
    out = _path(case, "design.npz")
    if os.path.exists(out):
        return
    cfg = CASES[case]
    fe, to_params = _hex(case)
    if cfg.get("gui_density"):
        rho = _gui_design(case, fe)
        final, objective, iterations = (rho >= 0.5).astype(float), None, None
        info = {"source": os.path.relpath(cfg["gui_density"], ROOT) + " >= 0.5 (GUI session)",
                "volume_fraction_continuous": float(rho.mean())}
        session = os.path.join(GUI_SESSION, "session.json")
        if os.path.exists(session):
            with open(session) as fh:
                rec = json.load(fh)
            objective, iterations = rec.get("objective_final"), rec.get("iterations")
    elif cfg["source"]:
        d = np.load(os.path.join(ROOT, cfg["source"]))
        if not np.allclose(d["node_xyz"], fe.mesh.node_xyz):
            raise RuntimeError(f"{case}: saved design is not on the benchmark mesh")
        # objective of the final 0/1 design (the showcase's summary.json), not history.npz's last continuous iterate
        with open(os.path.join(ROOT, os.path.dirname(cfg["source"]), "summary.json")) as fh:
            objective = float(json.load(fh)["objective_final"])
        final, iterations = d["final"], len(d["objective"])
        info = {"source": cfg["source"]}
    else:
        from pyto.topopt.drivers.mma import topopt_mma
        t0 = time.time()
        _u, history, _ok, msg, n_fe = topopt_mma(fe, to_params=to_params, maxMMAIterations=to_params.MaxIterations,
                                                 binarize_topology=not to_params.HeavisideProjection,
                                                 print_progress=False)
        final = np.asarray(fe.mesh.elemPseudoDensity, float)
        objective, iterations = float(np.asarray(history["objective"][-1]).reshape(-1)[0]), int(n_fe)
        info = {"source": "optimized here (MMA, AD, benchmark settings)", "time_s": time.time() - t0, "message": msg}
    np.savez_compressed(out, final=final, node_xyz=np.asarray(fe.mesh.node_xyz),
                        elems=np.asarray(fe.mesh.elemArray)[:, :8].astype(np.int64))
    info.update(objective_final_reported=objective, iterations=iterations, elements=int(fe.mesh.num_elems),
                dofs=int(3 * fe.mesh.num_nodes), volume_fraction=float(final.mean()))
    with open(_path(case, "design.json"), "w") as f:
        json.dump(info, f, indent=1)
    print(f"{case}: design ready ({info['source']}), volume fraction {final.mean():.3f}", flush=True)


