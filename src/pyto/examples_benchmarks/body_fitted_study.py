def _path(case, name):
    os.makedirs(os.path.join(OUT, case), exist_ok=True)
    return os.path.join(OUT, case, name)


def _recovered(case):
    """The recovered STL: the case's own (recover stage), or the GUI's for ThreeHoleBracketGUI."""
    return CASES[case].get("recovered") or _path(case, "recovered.stl")


def _tet_surface(case):
    """The surface the part's tet mesh is built from: the recovered STL, or (tet_surface_triangles) that STL
    simplified to about that many triangles (pyvista decimate_pro, topology preserved), written to
    <case>/recovered_tet_surface.stl. Returns (path, info)."""
    src, n = _recovered(case), CASES[case].get("tet_surface_triangles")
    if not n:
        return src, {}
    import pyvista as pv
    s = pv.read(src).triangulate()
    d = s.decimate_pro(1 - n / s.n_cells, preserve_topology=True).clean()
    out = _path(case, "recovered_tet_surface.stl")
    d.save(out)
    return out, {"surface_triangles_recovered": int(s.n_cells), "surface_triangles_meshed": int(d.n_cells),
                 "surface_volume_ratio_meshed_over_recovered": float(d.volume / s.volume)}


def _domain(case):
    """Design-domain STL: the benchmark's STL, or (EdgeCantilever, a generated grid box) a box of the hex mesh's
    bounds, written once to <case>/domain.stl."""
    if CASES[case]["domain"]:
        return os.path.join(ROOT, CASES[case]["domain"])
    out = _path(case, "domain.stl")
    if not os.path.exists(out):
        import pyvista as pv
        d = np.load(_path(case, "design.npz"))
        lo, hi = d["node_xyz"].min(0), d["node_xyz"].max(0)
        pv.Box(bounds=(lo[0], hi[0], lo[1], hi[1], lo[2], hi[2]), level=0, quads=False).triangulate().save(out)
    return out


def _hex(case):
    """Hex FE model of the case: the benchmark's (build_benchmark), or with nDOFDesired the same problem on another
    mesh, built as build_benchmark builds it (PARDISO)."""
    from pyto.examples_benchmarks.topopt_run_benchmarks import StructuralTOExamples, build_benchmark
    from pyto.solve.solvers import Solvers
    problem = getattr(StructuralTOExamples, CASES[case]["problem"])
    with contextlib.redirect_stdout(io.StringIO()):
        if "nDOFDesired" not in CASES[case]:
            fe, to_params, _ = build_benchmark(problem, solver=Solvers.PARDISO)
            return fe, to_params
        from pyto.examples_benchmarks.topopt_structural_benchmarks import getStructuralTOProblem
        from pyto.physics.structural.hex_structural_fea import HexStructuralFEA
        from pyto.solve import deflation
        mesh, mat_prop, bc, elem_body_force, to_params = getStructuralTOProblem(problem,
                                                                                nDOFDesired=CASES[case]["nDOFDesired"])
        fe = HexStructuralFEA(bc=bc, mesh=mesh, mat_prop=mat_prop, solver=Solvers.PARDISO,
                              dsolver=deflation.DeflationSolver(), rtol=1e-8, elem_body_force=elem_body_force)
    return fe, to_params


def _gui_design(case, fe):
    """The GUI session's voxel design (density >= 0.5) on fe's mesh; raises unless the GUI's .vtu mesh is that mesh
    (element count, node coordinates and connectivity)."""
    import pyvista as pv
    cfg = CASES[case]
    rho = np.load(cfg["gui_density"])
    g = pv.read(cfg["gui_mesh"])
    xyz, elems = np.asarray(fe.mesh.node_xyz, float), np.asarray(fe.mesh.elemArray)[:, :8]
    if not (len(rho) == g.n_cells == len(elems) and g.n_points == len(xyz)):
        raise RuntimeError(f"{case}: GUI density ({len(rho)} elements) / GUI mesh ({g.n_cells} elements, "
                           f"{g.n_points} nodes) is not the hex mesh ({len(elems)} elements, {len(xyz)} nodes)")
    if not (np.allclose(np.asarray(g.points, float), xyz, rtol=0, atol=1e-9)
            and np.array_equal(g.cells.reshape(-1, 9)[:, 1:], elems)):
        raise RuntimeError(f"{case}: GUI mesh {cfg['gui_mesh']} has other node coordinates or element order")
    return rho


