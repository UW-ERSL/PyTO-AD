def _camera(p, bounds, up):
    lo, hi = np.array(bounds[0::2]), np.array(bounds[1::2])
    c, diag = (lo + hi) / 2, np.linalg.norm(hi - lo)
    if tuple(up) == (0, 1, 0):
        direction = np.array([1.0, 0.75, 1.35])
    else:
        direction = np.array([1.0, 1.0, 1.0])
    direction /= np.linalg.norm(direction)
    p.camera_position = [tuple(c + 2.6 * diag * direction), tuple(c), tuple(up)]
    p.reset_camera(bounds=tuple(bounds))
    p.camera.zoom(1.05)


